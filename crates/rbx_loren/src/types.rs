//! `LorenTypes.luau` and `LorenServerTypes.luau` (`lib/types.js`): the module
//! names a project's typed `Dependencies` lists check against.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use crate::constants::{
    is_identifier, is_keyword, FOLDER_CONTROLLERS, FOLDER_SERVICES, SERVER_TYPES_FILE, TYPES_FILE,
};
use crate::ctx::{Names, TypesOptions, TypesResult};
use crate::fsutil::{
    is_dir, is_file, normalize_eol, read_text, read_text_if_exists, rel, write_text,
};
use crate::lint::{analyze_luau, is_networked, project_layout};
use crate::log::Log;

const FOLDER_SOURCES: [&str; 4] = ["init.luau", "init.lua", ".src.luau", ".src.lua"];

const SCRIPT_SUFFIXES: [&str; 5] = [".server", ".client", ".local", ".legacy", ".plugin"];

/// `(name, source file)` of each ModuleScript directly inside `dir`, by name.
pub fn list_modules(dir: &Path) -> Vec<(String, PathBuf)> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut names: Vec<String> = entries
        .filter_map(Result::ok)
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();
    let mut found: Vec<(String, PathBuf)> = Vec::new();
    // X.luau and X.lua: Rojo refuses; keep the first
    let mut add = |name: &str, file: PathBuf| {
        if !found.iter().any(|(n, _)| n == name) {
            found.push((name.to_string(), file));
        }
    };
    for name in names {
        let full = dir.join(&name);
        if is_dir(&full) {
            if let Some(source) = FOLDER_SOURCES
                .iter()
                .map(|f| full.join(f))
                .find(|p| is_file(p))
            {
                add(&name, source);
            }
            continue;
        }
        let lower = name.to_ascii_lowercase();
        let ext_len = if lower.ends_with(".luau") {
            5
        } else if lower.ends_with(".lua") {
            4
        } else {
            continue;
        };
        if name.len() == ext_len || !is_file(&full) {
            continue;
        }
        let base = &name[..name.len() - ext_len];
        let base_lower = base.to_ascii_lowercase();
        if SCRIPT_SUFFIXES.iter().any(|s| base_lower.ends_with(s)) {
            continue;
        }
        if base == "init" || base == ".src" {
            continue;
        }
        add(base, full);
    }
    found
}

fn luau_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            // three digits, so a digit after the escape is not read as part of it ("\1" .. "2" is not "\12")
            c if (c as u32) < 0x20 || c == '\x7f' => out.push_str(&format!("\\{:03}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn key_of(name: &str) -> String {
    if is_identifier(name) && !is_keyword(name) {
        name.to_string()
    } else {
        format!("[{}]", luau_string(name))
    }
}

fn union_type(alias: &str, names: &[String]) -> String {
    if names.is_empty() {
        return format!("export type {alias} = string -- none yet");
    }
    let quoted: Vec<String> = names.iter().map(|n| luau_string(n)).collect();
    let one = format!("export type {alias} = {}", quoted.join(" | "));
    if one.encode_utf16().count() <= 100 {
        return one;
    }
    format!("export type {alias} =\n\t{}", quoted.join("\n\t| "))
}

fn keyed_type(alias: &str, entries: &[(String, &str, Option<&str>)]) -> String {
    if entries.is_empty() {
        return format!("export type {alias} = {{ [string]: any }} -- none yet");
    }
    let lines: Vec<String> = entries
        .iter()
        .map(|(name, ty, note)| match note {
            Some(note) => format!("\t{}: {ty}, -- {note}", key_of(name)),
            None => format!("\t{}: {ty},", key_of(name)),
        })
        .collect();
    format!("export type {alias} = {{\n{}\n}}", lines.join("\n"))
}

const HEADER: &str =
    "-- AUTO-GENERATED by the Loren CLI (loren refresh, make, inject and update rewrite it). Do not edit.";

// Mirrors Loren's runtime types (LorenRuntime.Types) so this file needs no require.
const PROXY_TYPES: &str =
    "-- What a Controller gets for a networked Service (the same shape as Loren's ServiceProxy).
export type Connection = {
	Connected: boolean,
	Disconnect: (...any) -> (),
	Destroy: (...any) -> (),
}

export type ClientSignal = {
	Connect: (self: ClientSignal, fn: (...any) -> ()) -> Connection,
	Once: (self: ClientSignal, fn: (...any) -> ()) -> Connection,
	Wait: (self: ClientSignal) -> ...any,
	DisconnectAll: (self: ClientSignal) -> (),
}

export type ClientEvent = {
	Fire: (self: ClientEvent, ...any) -> (),
}

export type ServiceProxy = {
	Signals: { [string]: ClientSignal },
	ClientEvents: { [string]: ClientEvent },
	Try: { [string]: any },
	[string]: any,
}";

fn server_deps(services: &[String]) -> Vec<(String, &'static str, Option<&'static str>)> {
    services.iter().map(|n| (n.clone(), "any", None)).collect()
}

pub fn shared_source(names: &Names) -> String {
    let Names {
        services,
        controllers,
        networked,
    } = names;
    let all: BTreeSet<&String> = controllers.iter().chain(networked.iter()).collect();
    let client_deps: Vec<(String, &str, Option<&str>)> = all
        .into_iter()
        .map(|name| {
            let is_controller = controllers.contains(name);
            let is_service = networked.contains(name);
            if is_controller && is_service {
                (
                    name.clone(),
                    "any",
                    Some("a Controller and a networked Service: Loren refuses this at boot, rename one"),
                )
            } else {
                (name.clone(), if is_service { "ServiceProxy" } else { "any" }, None)
            }
        })
        .collect();
    [
        "--!strict".to_string(),
        HEADER.to_string(),
        String::new(),
        union_type("ServiceName", services),
        union_type("ControllerName", controllers),
        union_type("NetworkedServiceName", networked),
        "export type ClientDependencyName = ControllerName | NetworkedServiceName".to_string(),
        String::new(),
        PROXY_TYPES.to_string(),
        String::new(),
        keyed_type("ClientDeps", &client_deps),
        String::new(),
        keyed_type("ServerDeps", &server_deps(services)),
        String::new(),
        "return table.freeze({})".to_string(),
        String::new(),
    ]
    .join("\n")
}

pub fn server_source(names: &Names) -> String {
    [
        "--!strict".to_string(),
        HEADER.to_string(),
        String::new(),
        union_type("ServiceName", &names.services),
        union_type("NetworkedServiceName", &names.networked),
        String::new(),
        keyed_type("ServerDeps", &server_deps(&names.services)),
        String::new(),
        "return table.freeze({})".to_string(),
        String::new(),
    ]
    .join("\n")
}

/// Services, Controllers and networked Services, each sorted by code unit.
pub fn collect_names(
    root: &Path,
    shared_dir: &str,
    server_dir: &str,
    client_dir: &str,
    log: Option<&Log>,
) -> Names {
    let _ = shared_dir;
    let service_mods = list_modules(&root.join(server_dir).join(FOLDER_SERVICES));
    let controller_mods = list_modules(&root.join(client_dir).join(FOLDER_CONTROLLERS));
    let mut networked = Vec::new();
    for (name, file) in &service_mods {
        match read_text(file) {
            Ok(text) => {
                if is_networked(&analyze_luau(&text, None)) {
                    networked.push(name.clone());
                }
            }
            Err(err) => {
                if let Some(log) = log {
                    log.warn(&format!(
                        "Could not read {} for types: {err}",
                        rel(root, file)
                    ));
                }
            }
        }
    }
    let mut services: Vec<String> = service_mods.into_iter().map(|(n, _)| n).collect();
    let mut controllers: Vec<String> = controller_mods.into_iter().map(|(n, _)| n).collect();
    services.sort();
    controllers.sort();
    networked.sort();
    Names {
        services,
        controllers,
        networked,
    }
}

pub fn generate_types(root: &Path, opts: &TypesOptions) -> Result<TypesResult, String> {
    let layout =
        if opts.shared_dir.is_some() && opts.server_dir.is_some() && opts.client_dir.is_some() {
            None
        } else {
            Some(project_layout(root, None))
        };
    let pick = |given: &Option<String>, from: fn(&crate::lint::Layout) -> &String| -> String {
        match given {
            Some(d) if !d.is_empty() => d.clone(),
            _ => layout.as_ref().map(|l| from(l).clone()).unwrap_or_default(),
        }
    };
    let shared = pick(&opts.shared_dir, |l| &l.shared);
    let server = pick(&opts.server_dir, |l| &l.server);
    let client = pick(&opts.client_dir, |l| &l.client);

    let names = collect_names(root, &shared, &server, &client, opts.log);
    let server_dir = root.join(&server);
    let mut files = vec![(root.join(&shared).join(TYPES_FILE), shared_source(&names))];
    if is_dir(&server_dir) {
        files.push((server_dir.join(SERVER_TYPES_FILE), server_source(&names)));
    }

    let mut written = Vec::new();
    let mut planned = Vec::new();
    let mut unchanged = Vec::new();
    for (file, text) in &files {
        if read_text_if_exists(file).is_some_and(|current| normalize_eol(&current) == *text) {
            unchanged.push(file.clone());
            continue;
        }
        planned.push(file.clone());
        if !opts.dry_run {
            write_text(file, text)
                .map_err(|e| format!("Could not write {}: {e}", rel(root, file)))?;
            written.push(file.clone());
        }
    }
    Ok(TypesResult {
        written,
        planned,
        unchanged,
        files,
        names,
    })
}
